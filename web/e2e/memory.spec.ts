import { test, expect } from '@playwright/test'

test('长期记忆：明确保存、筛选、修改、冲突、清空和移动端', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/memories')
  await page.getByLabel('管理密钥').fill('test-only-management-key-32-bytes-long')
  await page.getByRole('button', { name: '进入管理后台' }).click()
  await page.getByRole('link', { name: '长期记忆' }).click()
  await expect(page.getByRole('heading', { name: '长期记忆', exact: true })).toBeVisible()
  await page.getByLabel('机器人 QQ', { exact: true }).fill('100')
  await page.getByLabel('对方 QQ / 群号').fill('200')
  await page.getByRole('button', { name: '查看范围' }).click()
  await page.getByLabel('保存类别').selectOption('preference')
  await page.getByLabel('记忆正文').fill('喜欢蓝色')
  await page.getByRole('button', { name: '保存记忆', exact: true }).click()
  await expect(page.getByRole('article').getByText('喜欢蓝色', { exact: true })).toBeVisible()
  await page.getByLabel('类别', { exact: true }).selectOption('fact')
  await expect(page.getByText('本页没有记忆。')).toBeVisible()
  await page.getByLabel('类别', { exact: true }).selectOption('')
  await page.getByRole('button', { name: /^编辑 #/ }).click()
  await page.getByLabel('记忆正文').fill('喜欢绿色')
  await page.getByRole('button', { name: '保存记忆', exact: true }).click()
  await expect(page.getByRole('article').getByText('喜欢绿色', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/memories-desktop.png', fullPage: true })
  await page.getByRole('button', { name: /^编辑 #/ }).click()
  await page.route('**/api/admin/v1/memories/*', async route => {
    if (route.request().method() === 'PATCH') await route.fulfill({ status: 409, contentType: 'application/json', body: JSON.stringify({ error: { code: 'memory_conflict', message: '记忆已变更，请刷新后重试' } }) })
    else await route.continue()
  })
  await page.getByRole('button', { name: '保存记忆', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('记忆已变更')
  await page.unrouteAll()
  await page.getByRole('button', { name: '取消编辑' }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'test-results/memories-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: '清空当前范围' }).click()
  await expect(page.getByRole('button', { name: '确认删除', exact: true })).toBeDisabled()
  await page.getByLabel('输入 100/private/200 确认').fill('100/private/200')
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByText('本页没有记忆。')).toBeVisible()
  expect(errors).toEqual([])
})
