import { test, expect } from '@playwright/test'

test('真实 Vite 代理：登录、素材预览、刷新会话、主题、退出', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/stickers')
  await expect(page.getByRole('heading', { name: '让管理回归简单。' })).toBeVisible()
  await page.getByLabel('管理密钥').fill('wrong')
  await page.getByRole('button', { name: '进入管理后台' }).click()
  await expect(page.getByRole('alert')).toContainText('管理密钥不正确')
  await page.getByLabel('管理密钥').fill('test-only-management-key-32-bytes-long')
  await page.getByRole('button', { name: '进入管理后台' }).click()
  await expect(page.getByRole('heading', { name: '测试欢迎图' })).toBeVisible()
  await expect(page.getByRole('img', { name: '测试欢迎图' })).toBeVisible()
  await expect.poll(() => page.getByRole('img', { name: '测试欢迎图' }).evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0)
  await page.screenshot({ path: 'test-results/stickers-desktop.png', fullPage: true })
  await page.reload()
  await expect(page.getByRole('heading', { name: '测试欢迎图' })).toBeVisible()
  await page.getByRole('button', { name: '深色模式' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: '查看详情' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('textbox', { name: '描述', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '预览 测试收藏图', exact: true }).click()
  await page.getByRole('textbox', { name: '描述', exact: true }).fill('适合开心打招呼，隔离测试描述')
  await page.getByRole('button', { name: '保存描述', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.getByText('适合开心打招呼，隔离测试描述')).toBeVisible()
  await page.getByLabel('选择 测试收藏图').check()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '批准使用', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('成功 1 项')
  await page.getByLabel('选择 测试收藏图').check()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '停用', exact: true }).click()
  await expect(page.getByRole('article').filter({ has: page.getByRole('heading', { name: '测试收藏图' }) }).getByText('已停用', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'test-results/stickers-mobile.png', fullPage: true })
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page.getByLabel('管理密钥')).toBeVisible()
  const response = await page.request.get('/api/admin/v1/stickers/demo/preview?source=local')
  expect(response.status()).toBe(401)
  expect(errors).toEqual([])
})
