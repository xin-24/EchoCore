import { test, expect } from '@playwright/test'

test('自动记忆：候选批准、删除抑制与暂停恢复', async ({ page }) => {
  await page.goto('/memories')
  await page.getByLabel('管理密钥').fill('test-only-management-key-32-bytes-long')
  await page.getByRole('button', { name: '进入管理后台' }).click()
  await page.getByRole('link', { name: '长期记忆' }).click()
  await page.getByLabel('机器人 QQ', { exact: true }).fill('100')
  await page.getByLabel('对方 QQ / 群号').fill('201')
  await page.getByRole('button', { name: '查看范围' }).click()
  await expect(page.getByRole('button', { name: /^审核候选 #/ })).toBeVisible()
  await page.getByRole('button', { name: /^审核候选 #/ }).click()
  await page.getByRole('button', { name: '确认批准', exact: true }).click()
  await expect(page.getByRole('button', { name: /^编辑 #/ })).toBeVisible()
  await expect(page.getByRole('button', { name: /^审核候选 #/ })).toHaveCount(0)
  await page.getByRole('button', { name: /^删除 #/ }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await page.getByRole('button', { name: '刷新候选' }).click()
  await expect(page.getByRole('button', { name: /^解除抑制 #/ })).toBeVisible()
  await page.getByRole('button', { name: /^解除抑制 #/ }).click()
  await expect(page.getByRole('button', { name: '确认解除', exact: true })).toBeDisabled()
  await page.getByLabel('输入 100/private/201 确认').fill('100/private/201')
  await page.getByRole('button', { name: '确认解除', exact: true }).click()
  await expect(page.getByRole('button', { name: /^解除抑制 #/ })).toHaveCount(0)
  await page.getByRole('button', { name: '暂停自动提取' }).click()
  await expect(page.getByRole('button', { name: '恢复自动提取' })).toBeEnabled()
  await page.getByRole('button', { name: '恢复自动提取' }).click()
  await expect(page.getByRole('button', { name: '暂停自动提取' })).toBeEnabled()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'test-results/memory-auto-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})
